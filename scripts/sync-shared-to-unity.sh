#!/usr/bin/env bash
# Copies the shared game core (shared/GangsOfBharat.Shared/**/*.cs) into the Unity project at
# client/GangsOfBharat.Unity/Assets/Scripts/Shared/ and writes its assembly definition.
#
# The copy is committed to git so a fresh clone opens in Unity without extra steps.
# Run this script after every change under shared/ and commit the result.
#
# Usage:
#   scripts/sync-shared-to-unity.sh          # copy (deletes stale .cs files in the target)
#   scripts/sync-shared-to-unity.sh --check  # exit 1 if the Unity copy is out of date
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC="$ROOT/shared/GangsOfBharat.Shared"
DST="$ROOT/client/GangsOfBharat.Unity/Assets/Scripts/Shared"

write_asmdef() {
  cat > "$1/GangsOfBharat.Shared.asmdef" <<'JSON'
{
    "name": "GangsOfBharat.Shared",
    "rootNamespace": "GangsOfBharat.Shared",
    "references": [],
    "includePlatforms": [],
    "excludePlatforms": [],
    "allowUnsafeCode": false,
    "overrideReferences": false,
    "precompiledReferences": [],
    "autoReferenced": true,
    "defineConstraints": [],
    "versionDefines": [],
    "noEngineReferences": true
}
JSON
}

# Fills the directory given as $1 with the shared sources and the asmdef.
build_copy() {
  local out="$1"
  (cd "$SRC" && find . -name '*.cs' -not -path './bin/*' -not -path './obj/*' -print0) |
    while IFS= read -r -d '' file; do
      mkdir -p "$out/$(dirname "$file")"
      cp "$SRC/$file" "$out/$file"
    done
  {
    echo "Generated by scripts/sync-shared-to-unity.sh. Do not edit files here;"
    echo "edit shared/GangsOfBharat.Shared/ and run the script again."
  } > "$out/README_GENERATED.txt"
  write_asmdef "$out"
}

if [[ "${1:-}" == "--check" ]]; then
  tmp="$(mktemp -d)"
  trap 'rm -rf "$tmp"' EXIT
  build_copy "$tmp"
  # Unity creates .meta files next to the copies; ignore them in the comparison.
  if diff -r -q -x '*.meta' "$tmp" "$DST"; then
    echo "Unity shared copy is up to date."
    exit 0
  fi
  echo "Unity shared copy is out of date. Run scripts/sync-shared-to-unity.sh" >&2
  exit 1
fi

mkdir -p "$DST"
# Remove stale copies (keep Unity .meta files so GUIDs stay stable for files that still exist).
find "$DST" -name '*.cs' -delete
build_copy "$DST"
# Drop .meta files whose source file no longer exists.
find "$DST" -name '*.cs.meta' | while read -r meta; do
  [[ -f "${meta%.meta}" ]] || rm -f "$meta"
done
count="$(find "$DST" -name '*.cs' | wc -l | tr -d ' ')"
echo "Copied $count shared .cs files to ${DST#"$ROOT"/}"
